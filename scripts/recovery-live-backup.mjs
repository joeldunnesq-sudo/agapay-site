import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { accountingHealthTotp } from './lib/accounting-health-totp.mjs';

const base = 'https://agapay.app';
const root = '/api/parish/dashboard/test-lubbock';
const recovery = root + '/portability/recovery';
// This operator can create backup points only. It never invokes restore, rollback,
// download, financial writes, or an operation that existed before this run.
export async function verifyLiveBackups({ env = process.env, fetchImpl = fetch } = {}) {
  const evidence = { checkedAt: new Date().toISOString(), passed: false, backupOnly: true, scopes: [] };
  let token = '',
    owned = null;
  async function request(path, body) {
    const permitted =
      body === undefined
        ? ['accounting', 'parish'].some((scope) => path === recovery + '?scope=' + scope)
        : path === root + '/session' ||
          path === '/api/mfa/verify' ||
          (path === recovery &&
            body.kind === 'backup' &&
            !body.snapshotId &&
            ['accounting', 'parish'].includes(body.scope)) ||
          (owned && [recovery + '/' + owned + '/advance', recovery + '/' + owned + '/cancel'].includes(path));
    assert.ok(permitted, 'Outside backup-only operator allowlist');
    const response = await fetchImpl(base + path, {
      method: body === undefined ? 'GET' : 'POST',
      redirect: 'error',
      signal: AbortSignal.timeout(180000),
      headers: {
        accept: 'application/json',
        ...(token ? { authorization: 'Bearer ' + token } : {}),
        ...(body === undefined ? {} : { 'content-type': 'application/json' }),
      },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const payload = await response.json();
    if (![200, 202].includes(response.status)) {
      evidence.httpStatus = response.status;
      if (/^[a-z_]{1,60}$/.test(payload?.code || '')) evidence.errorCode = payload.code;
      throw new Error('Backup check request failed');
    }
    return payload;
  }
  try {
    assert.ok(
      env.TEST_LUBBOCK_PARISH_PASSWORD && env.TEST_LUBBOCK_TOTP_SECRET,
      'Protected password and TOTP secret required'
    );
    const login = await request(root + '/session', { password: env.TEST_LUBBOCK_PARISH_PASSWORD });
    assert.ok(
      login.mfaRequired && !login.enrollmentRequired && login.methods?.includes('totp'),
      'Fresh authenticator verification required'
    );
    const verified = await request('/api/mfa/verify', {
      pendingToken: login.pendingToken,
      method: 'totp',
      code: accountingHealthTotp(env.TEST_LUBBOCK_TOTP_SECRET),
    });
    assert.ok(
      typeof verified.token === 'string' && verified.token.length && !verified.mfaRequired,
      'Authentication failed'
    );
    token = verified.token;
    for (const scope of ['accounting', 'parish']) {
      evidence.stage = scope;
      const before = await request(recovery + '?scope=' + scope);
      assert.ok(before.enabled && !before.operation, 'Recovery unavailable or another operation is active');
      const started = await request(recovery, { kind: 'backup', scope, requestKey: crypto.randomUUID() });
      let operation = started.operation;
      assert.ok(
        operation?.kind === 'backup' && operation.scope === scope && /^[a-f0-9-]{36}$/.test(operation.id),
        'Unexpected backup operation'
      );
      owned = operation.id;
      for (let step = 0; step < 20 && operation.status === 'running'; step++) {
        evidence.stage = scope + '-step-' + step;
        operation = (await request(recovery + '/' + owned + '/advance', {})).operation;
        assert.ok(
          operation?.id === owned && operation.kind === 'backup' && operation.scope === scope,
          'Backup operation identity changed'
        );
      }
      if (/^[a-z_]{1,60}$/.test(operation.errorCode || '')) evidence.errorCode = operation.errorCode;
      assert.equal(operation.status, 'completed', 'Backup did not complete');
      owned = null;
      const after = await request(recovery + '?scope=' + scope);
      assert.ok(!after.operation, 'Backup did not release the workspace');
      assert.ok(
        after.snapshots.some(
          (s) => s.id === operation.safetyId && s.scope === scope && s.status === 'ready' && s.verifiedAt
        ),
        'Verified restore point missing'
      );
      evidence.scopes.push({ scope, verified: true, workspaceReleased: true });
    }
    evidence.passed = true;
    evidence.stage = 'complete';
  } catch (error) {
    // Error text is generated by this operator, never by a provider response.
    evidence.failure = error.name === 'AssertionError' ? 'backup_contract_failed' : 'backup_request_failed';
    if (owned) {
      try {
        evidence.cancelledOwnBackup =
          (await request(recovery + '/' + owned + '/cancel', {})).operation?.status === 'cancelled';
      } catch {
        evidence.cancelledOwnBackup = false;
      }
    }
  }
  return evidence;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.length === 2)
    console.log(
      'Plan: create and verify two fresh Test Lubbock backup points with --run. No default network or writes; never restore.'
    );
  else {
    assert.deepEqual(process.argv.slice(2), ['--run']);
    assert.equal(process.env.GITHUB_ACTIONS, 'true');
    assert.equal(process.env.GITHUB_REF, 'refs/heads/main');
    const result = await verifyLiveBackups();
    await mkdir('artifacts/recovery-live', { recursive: true });
    await writeFile('artifacts/recovery-live/result.json', JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result));
    process.exitCode = result.passed ? 0 : 1;
  }
}
