import { readFileSync, writeFileSync } from 'node:fs';
import { loadAccountingMigrationManifest, validateAccountingMigrationManifest } from './lib/accounting-migration-ledger.mjs';

const manifest = validateAccountingMigrationManifest(process.cwd(), loadAccountingMigrationManifest(process.cwd()));
const target = 'src/accounting/provisioning/schema.generated.js';
const source = '// Generated by scripts/build-accounting-provisioning-schema.mjs. SQL checksums are immutable.\n'
  + manifest.migrations.map((item, index) => `import sql${index} from '../../../accounting-migrations/${item.name}';`).join('\n')
  + '\nexport const provisioningMigrations = [\n'
  + manifest.migrations.map((item, index) => `  { name: '${item.name}', sha256: '${item.sha256}', sql: sql${index} },`).join('\n') + '\n];\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== source) throw new Error('Rebuild the provisioning schema bundle.');
} else writeFileSync(target, source);
